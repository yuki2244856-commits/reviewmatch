create function public.is_admin() returns boolean
language sql stable security definer set search_path = '' as $$
  select exists (select 1 from public.profiles where id = auth.uid() and role = 'admin');
$$;
create function public.is_approved_user(p_user_id uuid) returns boolean
language sql stable security definer set search_path = '' as $$
  select exists (select 1 from public.profiles where id = p_user_id and status = 'approved');
$$;
revoke all on function public.is_admin(), public.is_approved_user(uuid) from public;
grant execute on function public.is_admin(), public.is_approved_user(uuid) to anon, authenticated;

-- app.js signUp supplies role/display_name and expects profiles before hydration.
create function public.handle_new_user() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  if new.raw_user_meta_data->>'role' not in ('company', 'creator')
    or new.raw_user_meta_data->>'role' is null then
    raise exception 'Invalid registration role';
  end if;
  insert into public.profiles(id, role, email, display_name, status)
  values (new.id, new.raw_user_meta_data->>'role', new.email,
    new.raw_user_meta_data->>'display_name', 'pending');
  return new;
end;
$$;
revoke all on function public.handle_new_user() from public;
create trigger on_auth_user_created after insert on auth.users
  for each row execute function public.handle_new_user();

